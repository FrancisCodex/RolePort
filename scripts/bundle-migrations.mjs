// Bundles drizzle/*.sql into lib/db/migrations.generated.ts so the browser database
// (lite mode, docs/LITE.md) can run the same migrations without a filesystem.
//   node scripts/bundle-migrations.mjs          write the file
//   node scripts/bundle-migrations.mjs --check  fail if it's out of date
import { readFileSync, writeFileSync } from "node:fs";
import { readMigrationFiles } from "drizzle-orm/migrator";

const OUT = "lib/db/migrations.generated.ts";
const migrations = readMigrationFiles({ migrationsFolder: "drizzle" });

const source = `// Generated by scripts/bundle-migrations.mjs from drizzle/. Do not edit; run \`npm run db:generate\`.
import type { MigrationMeta } from "drizzle-orm/migrator";

export const migrations: MigrationMeta[] = ${JSON.stringify(migrations, null, 2)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current.replace(/\r\n/g, "\n") !== source) {
    console.error(`${OUT} is out of date. Run: node scripts/bundle-migrations.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, source);
  console.log(`Wrote ${migrations.length} migrations to ${OUT}`);
}
