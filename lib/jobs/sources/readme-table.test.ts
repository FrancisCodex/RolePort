import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { JobSource, SourceKind } from "../types";
import { JOB_SOURCES } from "./registry";

/*
 * The README's "Job sources" table is generated from each source's metadata (kind, coverage,
 * needs, credit), so it can't drift from the code. `npm run docs:sources` rewrites it; this test
 * fails when it's out of date.
 */

const README = new URL("../../../README.md", import.meta.url);
const START = "<!-- sources:start (generated by npm run docs:sources) -->";
const END = "<!-- sources:end -->";

const KIND: Record<SourceKind, string> = {
  board: "Job board",
  official: "Official (government)",
  remote: "Remote jobs",
  company: "Company careers pages",
  "opt-in": "Opt-in scraper (self-hosted)",
};

type Row = { name: string; kind: string; coverage: string; needs: string };

/** The company boards are one row ("Companies you follow"), and so are the JobSpy boards. */
function rows(sources: JobSource[]): Row[] {
  const out: Row[] = [];
  const grouped = new Set<SourceKind>();
  for (const s of sources) {
    if (s.kind === "company" || s.kind === "opt-in") {
      if (grouped.has(s.kind)) continue;
      grouped.add(s.kind);
      const all = sources.filter((x) => x.kind === s.kind).map((x) => x.label);
      out.push({
        name: s.kind === "company" ? `Companies you follow (${all.join(", ")})` : `[JobSpy](#jobspy-linkedin-indeed-and-more): ${all.join(", ")}`,
        kind: KIND[s.kind],
        coverage: s.coverage,
        needs: s.needs ?? "Nothing",
      });
      continue;
    }
    out.push({ name: `[${s.label}](${s.attribution.url})`, kind: KIND[s.kind], coverage: s.coverage, needs: s.needs ?? "Nothing" });
  }
  return out;
}

export function sourcesTable(sources: JobSource[] = JOB_SOURCES): string {
  const lines = ["| Source | Kind | Where its jobs are | What you need |", "| --- | --- | --- | --- |"];
  for (const r of rows(sources)) lines.push(`| ${r.name} | ${r.kind} | ${r.coverage} | ${r.needs} |`);
  return lines.join("\n");
}

describe("README job sources table", () => {
  it("matches the sources in the code", () => {
    const readme = readFileSync(README, "utf8");
    const start = readme.indexOf(START);
    const end = readme.indexOf(END);
    expect(start, "README.md needs the sources markers").toBeGreaterThan(-1);
    const current = readme.slice(start + START.length, end).trim();
    const wanted = sourcesTable();
    if (process.env.UPDATE_SOURCES_TABLE) {
      writeFileSync(README, `${readme.slice(0, start + START.length)}\n${wanted}\n${readme.slice(end)}`);
      return;
    }
    expect(current, "Run `npm run docs:sources` to update the README").toBe(wanted);
  });
});
